export function getContinent(nationOrCountry: string): string {
  return COUNTRY_CONTINENT_MAP[nationOrCountry] || "Other";
}

export function isSameRegion(a: string, b: string): boolean {
  if (a.toLowerCase() === b.toLowerCase()) return true;
  const contA = getContinent(a);
  const contB = getContinent(b);
  return contA !== "Other" && contA === contB;
}

